function fixtureModule() {
  return `/*
 * Generated by scripts/e2e/enable-commerce-fixture.mjs in a scratch copy of the site, for the
 * commerce-on browser tests. It never exists in the repository. Catalogue reads answer from it when
 * the site has no Sanity client; every other read still answers \`null\`.
 */
import { LISTED_PRODUCTS_QUERY, PRODUCT_BY_SLUG_QUERY } from "./queries";

const PRODUCTS: ReadonlyArray<Record<string, unknown>> = ${JSON.stringify(PRODUCTS, null, 2)};

export function e2eCommerceFixture<T>(groq: string, params: Record<string, string>): T | null {
  if (groq === LISTED_PRODUCTS_QUERY) return PRODUCTS.filter((product) => product.status === "listed") as T;
  if (groq === PRODUCT_BY_SLUG_QUERY) return (PRODUCTS.find((product) => product.slug === params.slug) ?? null) as T | null;
  return null;
}
`;
}

const isWithin = (folder, parent) => {
  const path = relative(parent, folder);
  return path === "" || (!path.startsWith("..") && !isAbsolute(path));
};

/** The nearest folder, the target itself included, holding a `.git` folder or file; null if none. */
function gitWorkTreeOf(folder) {
  for (let current = folder; ; current = dirname(current)) {
    if (existsSync(join(current, ".git"))) return current;
    if (dirname(current) === current) return null;
  }
}

/** Why the folder must not be touched, or null when it is a scratch copy of this site. */
export function refusalFor(target) {
  if (!existsSync(target) || !statSync(target).isDirectory()) return `${target}: no such folder`;
  const folder = realpathSync(target);
  const repository = realpathSync(REPOSITORY);
  if (folder === repository) return `${folder} is this repository itself; copy it to a scratch folder first`;
  if (isWithin(folder, repository)) return `${folder} is inside this repository`;
  const workTree = gitWorkTreeOf(folder);
  if (workTree) return `${folder} is inside a git work tree (${workTree}); use a copy without git, outside any repository`;
  const missing = COPY_MARKERS.filter((file) => !existsSync(join(folder, file)));
  if (missing.length > 0) return `${folder} is not a copy of this site (missing ${missing.join(", ")})`;
  return null;
}

/** Applies the fixture to a scratch copy. Throws, having written nothing, if anything is off. */
export function enableCommerceFixture(target) {
  const refusal = refusalFor(target);
  if (refusal) throw new Error(`refused: ${refusal}`);
  const folder = realpathSync(target);
  const contents = new Map();
  const read = (file) => contents.get(file) ?? readFileSync(join(folder, file), "utf8").replace(/\r\n/g, "\n");
  const fixture = fixtureModule();
  const fixturePath = join(folder, FIXTURE_MODULE);
  // A patch is in place when its replacement is (the import's replacement contains the original).
  const alreadyDone = PATCHES.every(({ file, to }) => read(file).includes(to)) && existsSync(fixturePath) && readFileSync(fixturePath, "utf8") === fixture;
  if (alreadyDone) return { changed: [] };

  for (const { file, from, to } of PATCHES) {
    const text = read(file);
    if (text.includes(to)) continue;
    const count = text.split(from).length - 1;
    if (count !== 1) throw new Error(`${file} has changed: expected one ${JSON.stringify(from.trim())}, found ${count}. Update scripts/e2e/enable-commerce-fixture.mjs.`);
    contents.set(file, text.replace(from, to));
  }
  // Everything checked: now write.
  for (const [file, text] of contents) writeFileSync(join(folder, file), text);
  writeFileSync(fixturePath, fixture);
  return { changed: [...contents.keys(), FIXTURE_MODULE] };
}

function main(args) {
  if (args.length !== 1) {
    console.error("usage: node scripts/e2e/enable-commerce-fixture.mjs <scratch copy>");
    return 2;
  }
  try {
    const { changed } = enableCommerceFixture(resolve(args[0]));
    console.log(changed.length === 0 ? "The commerce fixture is already in place; nothing changed." : `Commerce fixture enabled; changed ${changed.join(", ")}.`);
    return 0;
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    return 1;
  }
}

