const ASSIGNED = new Set(ORDER_COUNTRY_CODES);

/** The Studio's check of `orderCountries`: true, or the problem to show the editor. */
export function orderCountriesProblem(value: unknown): string | true {
  const codes = Array.isArray(value) ? value : [];
  const unknown = codes.filter((code) => typeof code !== "string" || !ASSIGNED.has(code)).map(String);
  if (unknown.length > 0) return `Use two-letter ISO 3166-1 codes in capitals, such as GB or PH. Not a country code: ${unknown.join(", ")}`;
  if (new Set(codes).size !== codes.length) return "Each country may appear only once";
  return true;
}
